/**
 * 3. Политика в отношении использования файлов cookie (мини-файлов с информацией)
 */
export function getCookiePolicyTemplate(params: LegalTemplateParams): string {
  const org = params.orgName || "Наименование организации / ИП";
  const domain = params.domain ? params.domain.replace(/\/+$/, "") : "https://ваш-домен.ru";

  return `ПОЛИТИКА В ОТНОШЕНИИ ИСПОЛЬЗОВАНИЯ ФАЙЛОВ COOKIE

1. ЧТО ТАКОЕ ФАЙЛЫ COOKIE
Файлы cookie (куки) — это небольшие текстовые фрагменты данных, сохраняемые на вашем компьютере или мобильном устройстве при посещении сайта ${domain}. Они позволяют сайту запоминать ваши действия и предпочтения (например, состояние диалога в чате, сессию пользователя, выбранный город или специалиста) на определенный период времени.

2. ДЛЯ ЧЕГО МЫ ИСПОЛЬЗУЕМ COOKIE
${org} использует файлы cookie в следующих целях:
  • Строго технические (необходимые): поддержание стабильной сессии пользователя, сохранение контекста общения с интерактивным помощником при перезагрузке страницы, защита от спама (CSRF);
  • Функциональные: запоминание ваших индивидуальных настроек интерфейса;
  • Статистические и аналитические: обезличенный учет количества посетителей, популярных страниц и эффективности интерактивных виджетов для улучшения удобства Сайта.

3. КАКИЕ ФАЙЛЫ COOKIE ИСПОЛЬЗУЮТСЯ
  • Сессионные (временные) файлы: существуют только пока открыт браузер, и удаляются при его закрытии.
  • Постоянные файлы: остаются на устройстве в течение заданного срока действия или до момента их удаления пользователем.

4. УПРАВЛЕНИЕ ФАЙЛАМИ COOKIE
4.1. Большинство веб-браузеров автоматически принимают файлы cookie по умолчанию, однако вы можете изменить настройки своего браузера, чтобы блокировать файлы cookie или получать предупреждения перед их сохранением.
4.2. Обратите внимание: полное отключение необходимых файлов cookie может привести к некорректной работе интерактивных элементов сайта (виджетов чата, выбора специалистов и сохранения заявок).
4.3. Продолжая использовать сайт ${domain} без изменения настроек браузера, вы выражаете свое согласие на использование файлов cookie в соответствии с условиями настоящей Политики.`;
}

