/**
 * Локальный санитайзер персональных данных (Phase 2).
 *
 * Назначение:
 *   Любой текст, идущий из формы пользователя в сеть (в ИИ-Архитектор),
 *   проходит через `sanitize(text, aliases)` до отправки. На выход
 *   получается безопасный черновик + перечень того, что было вырезано,
 *   чтобы UI мог явно показать психологу: «Внимание, мы автоматически
 *   удалили из текста: Телефон, Имя».
 *
 * Архитектурные принципы:
 *   * Чистая функция: нет I/O, нет сети, нет глобального состояния.
 *   * Карта алиасов (Иванов → Ученик №1) приходит снаружи и хранится
 *     **только в RAM терминала**. Здесь мы её только используем,
 *     а не загружаем и не пишем.
 *   * Порядок применения детекторов фиксирован: e-mail / СНИЛС / паспорт
 *     идут раньше телефона, чтобы более узкие паттерны не «съели»
 *     цифровые куски более широкими.
 *   * Адресный детектор намеренно консервативный — он ловит явные
 *     префиксы «г. / ул. / пр.», а не пытается угадывать топонимы.
 *     Лучше пропустить редкий случай, чем подменить полезное содержание.
 */

export interface SanitizeResult {
  /** Очищенный текст, готовый к отправке в ИИ-Архитектор. */
  sanitizedText: string;
  /** Было ли хоть одно срабатывание детекторов. */
  hasMatches: boolean;
  /** Дедуплицированный список типов вырезанных сущностей. */
  detectedTypes: DetectedType[];
}

/**
 * Локальная карта алиасов: «ФИО или короткое имя → нейтральный маркер».
 * Источник — таблица `pd_aliases` в зашифрованной локальной БД.
 * На сервер эта карта НЕ уходит ни при каких обстоятельствах.
 */
export interface AliasMap {
  [originalName: string]: string;
}

export type DetectedType =
  | "Name"
  | "Email"
  | "Phone"
  | "Document"
  | "Organization"
  | "Address";

// ---------------------------------------------------------------------------
// Регулярные детекторы (порядок применения — см. ниже в `sanitize`).
// ---------------------------------------------------------------------------

// E-mail (упрощённый, но достаточно широкий для типичных адресов).
const EMAIL_RE = /[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}/g;

// СНИЛС: «123-456-789 01». Дефисный формат — самый специфичный, идёт первым.
const SNILS_RE = /\b\d{3}-\d{3}-\d{3}\s\d{2}\b/g;

// Паспорт РФ: серия (4 цифры, разрешён пробел внутри) + номер (6 цифр),
// с опциональным разделителем «№». Примеры:
//   "4500 123456", "45 00 123456", "4500 № 123456", "45 00 № 123456".
const PASSPORT_RE = /\b\d{2}\s?\d{2}\s?(?:№\s?)?\d{6}\b/g;

// Кандидат на телефон. Финальная проверка — по количеству цифр в `sanitize`
// (10..15 digits), чтобы не подменять годы, артикулы, серийные номера.
const PHONE_CANDIDATE_RE = /(\+?\d[\d\s\-().]{7,}\d)/g;

// Организация (Школа / Гимназия / Лицей / МБОУ / ГБОУ / МАОУ / МОУ / СОШ),
// с обязательным номером после неё.
const ORG_RE = /(?:Школ[аы]|Гимнази[яи]|Лицей|МБОУ|ГБОУ|МАОУ|МОУ|СОШ)\s*(?:№|#)?\s*\d+/giu;

// Адресные префиксы: г., город, ул., улица, пр., проспект, пер., переулок,
// пл., площадь, д., дом — с топонимом (заглавная буква + остаток).
// Сознательно НЕ ловим почтовые индексы (6 цифр) — слишком много
// false-positive с паспортными номерами и артикулами.
const ADDRESS_RE =
  /(?:г\.|город|ул\.|улица|пр\.|проспект|пер\.|переулок|пл\.|площадь|д\.|дом)\s+[А-ЯЁ][А-Яа-яёЁ\-]+(?:\s+\d+[а-яё]?)?/giu;

// ---------------------------------------------------------------------------
// Утилиты
// ---------------------------------------------------------------------------

/** Экранирование спецсимволов перед подстановкой в RegExp. */
function escapeRegExp(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/**
 * Word-boundary, дружественный к кириллице. Стандартный `\b` в JS работает
 * только с латиницей, поэтому строим явные lookaround'ы.
 */
function buildAliasRegex(name: string): RegExp {
  const escaped = escapeRegExp(name);
  return new RegExp(
    `(?<![А-Яа-яёЁA-Za-z])${escaped}(?![А-Яа-яёЁA-Za-z])`,
    "gu",
  );
}

// ---------------------------------------------------------------------------
// Главная функция
// ---------------------------------------------------------------------------

/**
 * Очистить текст от персональных данных перед отправкой в ИИ-Архитектор.
 *
 * Фаза А — алиасы. Проходим по `localAliases` (известные ФИО и короткие
 *   имена из карточки кейса) и заменяем их на нейтральный маркер.
 *
 * Фаза Б — регулярки. По очереди прогоняем e-mail / СНИЛС / паспорт /
 *   телефон / организация / адрес. Замены — стабильные строки в квадратных
 *   скобках, чтобы UI и сервер могли их различать.
 *
 * Фаза В — отчёт. Возвращаем `SanitizeResult` с дедуплицированным списком
 *   типов сработавших детекторов (для предупреждения психологу).
 */
export function sanitize(text: string, localAliases: AliasMap = {}): SanitizeResult {
  if (!text) {
    return { sanitizedText: "", hasMatches: false, detectedTypes: [] };
  }

  let sanitized = text;
  const detected = new Set<DetectedType>();

  // --- Фаза А: замены по локальному словарю алиасов ------------------------
  // Сортируем по длине ключа убыванием — иначе короткое имя «Петя» может
  // съесть часть длинного «Петя Иванов» до того, как мы попытаемся
  // заменить полное ФИО.
  const aliasEntries = Object.entries(localAliases)
    .filter(([k]) => typeof k === "string" && k.length > 0)
    .sort((a, b) => b[0].length - a[0].length);

  for (const [name, marker] of aliasEntries) {
    const re = buildAliasRegex(name);
    const before = sanitized;
    sanitized = sanitized.replace(re, marker);
    if (sanitized !== before) {
      detected.add("Name");
    }
  }

  // --- Фаза Б: регулярные детекторы (порядок важен!) ----------------------

  // 1. E-mail — самый «узкий» паттерн, забираем первым.
  {
    const before = sanitized;
    sanitized = sanitized.replace(EMAIL_RE, "[Email]");
    if (sanitized !== before) detected.add("Email");
  }

  // 2. СНИЛС (специфичный формат с дефисами).
  {
    const before = sanitized;
    sanitized = sanitized.replace(SNILS_RE, "[Документ]");
    if (sanitized !== before) detected.add("Document");
  }

  // 3. Паспорт — забираем ДО телефона, иначе 10 цифр серии+номера
  //    могут попасть в кандидат-телефон.
  {
    const before = sanitized;
    sanitized = sanitized.replace(PASSPORT_RE, "[Документ]");
    if (sanitized !== before) detected.add("Document");
  }

  // 4. Телефон — двухшаговый: regex ловит кандидата, потом мы считаем цифры.
  sanitized = sanitized.replace(PHONE_CANDIDATE_RE, (match) => {
    const digits = match.replace(/\D/g, "");
    if (digits.length >= 10 && digits.length <= 15) {
      detected.add("Phone");
      return "[Телефон]";
    }
    return match;
  });

  // 5. Организация (школа / гимназия / лицей и т.п. + номер).
  {
    const before = sanitized;
    sanitized = sanitized.replace(ORG_RE, "[Организация]");
    if (sanitized !== before) detected.add("Organization");
  }

  // 6. Адрес — последним, чтобы не накладываться на остальные.
  {
    const before = sanitized;
    sanitized = sanitized.replace(ADDRESS_RE, "[Адрес]");
    if (sanitized !== before) detected.add("Address");
  }

  return {
    sanitizedText: sanitized,
    hasMatches: detected.size > 0,
    detectedTypes: Array.from(detected),
  };
}

