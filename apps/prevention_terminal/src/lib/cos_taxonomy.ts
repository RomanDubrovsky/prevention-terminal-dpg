// ---------------------------------------------------------------------------
// 7. Поля журнала учёта индивидуальной работы (PDF export)
// ---------------------------------------------------------------------------
export interface CosJournalEntry {
  /** № п/п */
  index: number;
  /** Дата консультации */
  date: string;
  /** ФИО клиента (или псевдоним) */
  fullName: string;
  /** Дата рождения */
  birthDate: string;
  /** Тематика обращения */
  topic: string;
  /** Целевая категория */
  targetCategory: CosTargetCategory;
  /** Проблемы (список) */
  problems: string;
  /** Вид деятельности */
  activityKind: string;
  /** Статус консультации */
  status: CosStatus | string;
  /** Повторное обращение (Да / Да (до [дата]) / —) */
  isRepeat: string;
  /** Консультация иного специалиста в области здравоохранения */
  healthReferral: string;
  /** Консультация иного специалиста в области защиты прав */
  rightsReferral: string;
}

