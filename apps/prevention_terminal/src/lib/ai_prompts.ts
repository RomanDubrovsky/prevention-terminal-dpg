export function sectionArchitectPrompt(category: string, stage: "plan" | "report"): string {
  const key = `${category}_${stage}`;
  return SECTION_ARCHITECT_PROMPTS[key] || SECTION_ARCHITECT_PROMPTS.group_plan;
}

export function sectionExpertPrompt(protocolId: string): string {
  return (
    SECTION_EXPERT_PROMPTS[protocolId] ||
    EXPERT_DEFAULT_PROMPTS[protocolId] ||
    EXPERT_DEFAULT_PROMPTS.audit
  );
}

export function getFillCardPrompt(category: string): string {
  return FILL_CARD_PROMPTS[category] || FILL_CARD_PROMPTS.default;
}
